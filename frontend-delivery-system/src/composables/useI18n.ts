// ── Singleton reactive state ───────────────────────────────────────────────
const _lang = ref<Lang>((localStorage.getItem('lang') as Lang) || 'en')

export function useI18n() {
  function setLang(l: Lang) {
    _lang.value = l
    localStorage.setItem('lang', l)
    // Update <html lang> attribute for accessibility
    document.documentElement.lang = l === 'km' ? 'km' : 'en'
  }

  const t = computed(() => messages[_lang.value])
  const lang = computed(() => _lang.value)
  const isKhmer = computed(() => _lang.value === 'km')

  return { t, lang, isKhmer, setLang }
}
